export function buildInvoiceText(input: LegalDocInput): string {
  const ex = input.executor;
  const sign = ex.signatoryName || ex.shortName;
  const n = Math.round(input.amount).toLocaleString("ru-RU");
  return [
    ex.fullName || ex.shortName,
    `ИНН: ${ex.inn}    ОГРНИП: ${ex.ogrnip}`,
    ex.legalAddress,
    `Р/счёт: ${input.bank.account}`,
    input.bank.bankName,
    `Кор/счёт: ${input.bank.corrAccount}    БИК: ${input.bank.bik}`,
    ex.phone ? `Тел: ${ex.phone}` : "",
    ex.email ? `E-mail: ${ex.email}` : "",
    "",
    `Счёт на оплату № ${input.contractNumber || "___"} от ${input.contractDate}`,
    "",
    `Заказчик: ${input.customer.companyName || "—"}`,
    input.customer.inn ? `ИНН заказчика: ${input.customer.inn}` : "",
    "",
    `1. Техническое сопровождение мероприятия ${subjectLine(input)} — ${n} ₽`,
    "",
    `Итого: ${n} ₽`,
    "НДС не облагается в связи с применением Исполнителем АУСН.",
    "",
    `Всего к оплате: ${n} (${rublesInWords(input.amount)})`,
    "",
    `Предприниматель  ______________________/${sign}/`,
  ]
    .filter((line, i, arr) => line !== "" || arr[i - 1] !== "")
    .join("\n");
}

